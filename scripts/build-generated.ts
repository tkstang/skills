interface ImportRewrite {
  from: string;
  to: string;
}

export interface GeneratedOutput {
  id: string;
  source: string;
  output: string;
  bundle?: boolean;
  pendingUntilSourceExists?: boolean;
  importRewrites?: readonly ImportRewrite[];
}

interface ParsedOptions {
  check: boolean;
  help: boolean;
  listOutputs: boolean;
}

interface BuiltMapping {
  mapping: GeneratedOutput;
  status: 'built';
  outputPath: string;
  text: string;
  mode: number;
  inputFingerprint: string;
}

interface PendingMapping {
  mapping: GeneratedOutput;
  status: 'pending';
  message: string;
}


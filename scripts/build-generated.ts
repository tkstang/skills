function usage() {
  return `Usage: pnpm tsx scripts/build-generated.ts [--check] [--list-outputs]

Build committed generated runtime outputs from canonical TypeScript sources.

Options:
  --check   Compare generated output with committed files without writing.
  --list-outputs
            Print generated output paths, one per line.
  --help    Show this help.
`;
}

function parseArgs(argv: readonly string[]): ParsedOptions {
  const options = { check: false, help: false, listOutputs: false };

  for (const arg of argv) {
    if (arg === '--check') {
      options.check = true;
    } else if (arg === '--list-outputs') {
      options.listOutputs = true;
    } else if (arg === '--help' || arg === '-h') {
      options.help = true;
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }

  if (options.check && options.listOutputs) {
    throw new Error('Use only one of --check or --list-outputs');
  }

  return options;
}

async function readIfExists(filePath: string): Promise<string | null> {
  try {
    return await readFile(filePath, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
    throw error;
  }
}

function bannerFor(mapping: GeneratedOutput): string {
  return `${GENERATED_BANNER_PREFIX}
// Source: ${mapping.source}`;
}

function replacementFor(specifier: string): string {
  return `'${specifier}'`;
}

// Walks the AST of an emitted (or emitted-shaped) module, invoking `visitor`
// with every static or dynamic module-specifier string-literal node: import
// declarations, `export ... from`, and dynamic `import(...)` calls. Shared by
// the rewrite applier and the rewrite deriver so both recognize exactly the
// same set of import forms.
function forEachModuleSpecifierNode(
  sourceFile: ts.SourceFile,
  visitor: (moduleSpecifier: ts.StringLiteral) => void,
): void {
  function addModuleSpecifier(moduleSpecifier: ts.Expression) {
    if (!ts.isStringLiteral(moduleSpecifier)) return;
    visitor(moduleSpecifier);
  }

  function visit(node: ts.Node): void {
    if (ts.isImportDeclaration(node)) {
      addModuleSpecifier(node.moduleSpecifier);
    } else if (ts.isExportDeclaration(node) && node.moduleSpecifier) {
      addModuleSpecifier(node.moduleSpecifier);
    } else if (
      ts.isCallExpression(node) &&
      node.expression.kind === ts.SyntaxKind.ImportKeyword &&
      node.arguments.length > 0
    ) {
      addModuleSpecifier(node.arguments[0]);
    }

    ts.forEachChild(node, visit);
  }

  visit(sourceFile);
}

export function rewriteImportSpecifiers(
  text: string,
  rewrite: ImportRewrite,
  mappingId: string,
): string {
  const sourceFile = ts.createSourceFile(
    `${mappingId}.mjs`,
    text,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.JS,
  );
  const replacements: Array<{ start: number; end: number; text: string }> = [];

  forEachModuleSpecifierNode(sourceFile, (moduleSpecifier) => {
    if (moduleSpecifier.text !== rewrite.from) return;

    replacements.push({
      start: moduleSpecifier.getStart(sourceFile),
      end: moduleSpecifier.getEnd(),
      text: replacementFor(rewrite.to),
    });
  });

  if (replacements.length === 0) {
    throw new Error(
      `Import rewrite for ${mappingId} expected emitted output to contain module specifier ${rewrite.from}`,
    );
  }

  let rewritten = text;
  for (const replacement of replacements.toSorted(
    (a, b) => b.start - a.start,
  )) {
    rewritten =
      rewritten.slice(0, replacement.start) +
      replacement.text +
      rewritten.slice(replacement.end);
  }

  return rewritten;
}

// Returns every relative ('./' or '../') module specifier that appears in
// emitted (pre-rewrite) output, de-duplicated and in first-seen order.
// Type-only imports never reach this list: esbuild already elides them from
// the emitted JS before this function ever sees the text.
export function collectRelativeModuleSpecifiers(
  text: string,
  mappingId: string,
): string[] {
  const sourceFile = ts.createSourceFile(
    `${mappingId}.mjs`,
    text,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.JS,
  );
  const specifiers: string[] = [];
  const seen = new Set<string>();

  forEachModuleSpecifierNode(sourceFile, (moduleSpecifier) => {
    const specifier = moduleSpecifier.text;
    if (!specifier.startsWith('./') && !specifier.startsWith('../')) return;
    if (seen.has(specifier)) return;
    seen.add(specifier);
    specifiers.push(specifier);
  });

  return specifiers;
}

// Resolves a relative module specifier emitted for `mapping` back to the
// repo-relative canonical source path it was compiled from (reversing
// esbuild/tsc's convention of writing '.js' specifiers for '.ts' sources).
function resolveSpecifierSource(
  mapping: GeneratedOutput,
  specifier: string,
): string {
  const specifierAsSource = specifier.replace(/\.js$/, '.ts');
  return path.posix.normalize(
    path.posix.join(path.posix.dirname(mapping.source), specifierAsSource),
  );
}

// Some canonical sources (e.g. consensus-config.ts, transcript core
// runtimes.ts) fan out to more than one generated output — one per consuming
// skill. Disambiguate by picking the candidate whose output directory shares
// the longest path-prefix with the importing mapping's own output directory
// (the consuming skill's own generated copy is always the closest one).
function pickImportRewriteTarget(
  mapping: GeneratedOutput,
  candidates: readonly GeneratedOutput[],
): GeneratedOutput {
  if (candidates.length === 1) return candidates[0];

  const currentDir = path.posix.dirname(mapping.output).split('/');
  let best: GeneratedOutput | null = null;
  let bestScore = -1;
  let tied = false;

  for (const candidate of candidates) {
    const candidateDir = path.posix.dirname(candidate.output).split('/');
    let score = 0;
    while (
      score < currentDir.length &&
      score < candidateDir.length &&
      currentDir[score] === candidateDir[score]
    ) {
      score += 1;
    }

    if (score > bestScore) {
      bestScore = score;
      best = candidate;
      tied = false;
    } else if (score === bestScore) {
      tied = true;
    }
  }

  if (tied) {
    throw new Error(
      `Import rewrite derivation for ${mapping.id} found multiple equally-close generated-output candidates; add an explicit importRewrites override to disambiguate.`,
    );
  }

  if (!best) throw new Error(`No import rewrite candidates for ${mapping.id}`);
  return best;
}

// Derives importRewrites for `mapping` from the module specifiers actually
// present in its emitted (pre-rewrite) output, rather than a hand-maintained
// per-entry list. Every relative specifier must resolve to a known
// generatedOutputs source — an unresolvable specifier is a loud build error,
// never a silent skip.
export function deriveImportRewrites(
  mapping: GeneratedOutput,
  emittedText: string,
): ImportRewrite[] {
  const specifiers = collectRelativeModuleSpecifiers(emittedText, mapping.id);
  const rewrites: ImportRewrite[] = [];

  for (const specifier of specifiers) {
    const resolvedSource = resolveSpecifierSource(mapping, specifier);
    const candidates = generatedOutputs.filter(
      (candidate) => candidate.source === resolvedSource,
    );

    if (candidates.length === 0) {
      throw new Error(
        `Import rewrite derivation for ${mapping.id} found module specifier '${specifier}' resolving to '${resolvedSource}', which has no generatedOutputs entry. Add a mapping for it or add an explicit importRewrites override.`,
      );
    }

    const target = pickImportRewriteTarget(mapping, candidates);
    const fromDir = path.posix.dirname(mapping.output);
    let to = path.posix.relative(fromDir, target.output);
    if (!to.startsWith('.')) to = `./${to}`;

    rewrites.push({ from: specifier, to });
  }

  return rewrites;
}

async function buildMapping(
  mapping: GeneratedOutput,
  root: string = repoRoot,
): Promise<BuiltMapping | PendingMapping> {
  const sourcePath = path.join(root, mapping.source);
  const outputPath = path.join(root, mapping.output);
  const source = await readIfExists(sourcePath);

  if (source === null && mapping.pendingUntilSourceExists) {
    return {
      mapping,
      status: 'pending',
      message: `${mapping.source} does not exist yet`,
    };
  }

  if (source === null) {
    throw new Error(`Missing generated-output source: ${mapping.source}`);
  }

  const result = await build({
    absWorkingDir: root,
    entryPoints: [mapping.source],
    outfile: outputPath,
    bundle: mapping.bundle ?? false,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    write: false,
    metafile: true,
    legalComments: 'none',
    logLevel: 'silent',
    banner: {
      js: bannerFor(mapping),
    },
  });

  const outputFile = result.outputFiles?.[0];
  if (!outputFile) {
    throw new Error(`No generated output emitted for ${mapping.id}`);
  }

  let text = outputFile.text;
  const rewrites =
    mapping.importRewrites ?? deriveImportRewrites(mapping, text);
  for (const rewrite of rewrites) {
    text = rewriteImportSpecifiers(text, rewrite, mapping.id);
  }
  const inputFingerprint = createHash('sha256');
  for (const input of Object.keys(result.metafile.inputs).toSorted()) {
    const absolute = path.resolve(root, input);
    const info = await lstat(absolute);
    inputFingerprint.update(input);
    inputFingerprint.update(String(info.mode & 0o777));
    inputFingerprint.update(await readFile(absolute));
  }

  return {
    mapping,
    status: 'built',
    outputPath,
    text,
    inputFingerprint: inputFingerprint.digest('hex'),
    mode: await lstat(outputPath)
      .then((info) => info.mode & 0o777)
      .catch((error: NodeJS.ErrnoException) => {
        if (error.code === 'ENOENT') return 0o644;
        throw error;
      }),
  };
}

function firstDifference(actual: string, expected: string): number {
  const max = Math.min(actual.length, expected.length);
  for (let index = 0; index < max; index += 1) {
    if (actual[index] !== expected[index]) return index;
  }
  return actual.length === expected.length ? -1 : max;
}

export const generatedOutputRoots = [
  ...generatedOutputs.map((mapping) => mapping.output),
  ...distributions.flatMap((distribution) =>
    distribution.targets.map((target) => target.output),
  ),
];

export function isGeneratedOutputPath(
  relativePath: string,
  roots: readonly string[] = generatedOutputRoots,
): boolean {
  const normalized = relativePath
    .split(path.sep)
    .join('/')
    .replace(/^\.\//u, '');
  return roots.some(
    (root) => normalized === root || normalized.startsWith(`${root}/`),
  );
}

async function listFiles(directory: string): Promise<string[]> {
  const entries = await readdir(directory, { withFileTypes: true }).catch(
    (error: NodeJS.ErrnoException) => {
      if (error.code === 'ENOENT') return [];
      throw error;
    },
  );
  const files: string[] = [];
  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await listFiles(entryPath)));
    else if (entry.isFile()) files.push(entryPath);
  }
  return files;
}

async function findOrphanGeneratedFiles(
  root: string,
  mappings: readonly GeneratedOutput[],
): Promise<string[]> {
  const expected = new Set(mappings.map((mapping) => mapping.output));
  const outputDirectories = new Set(
    mappings.map((mapping) => path.posix.dirname(mapping.output)),
  );
  const orphans: string[] = [];
  for (const directory of outputDirectories) {
    for (const file of await listFiles(path.join(root, directory))) {
      const relative = path.relative(root, file).split(path.sep).join('/');
      if (expected.has(relative)) continue;
      const contents = await readFile(file, 'utf8').catch(() => '');
      if (
        /^\/\/ GENERATED by scripts\/build-generated\.(?:mjs|ts)\./u.test(
          contents,
        )
      ) {
        orphans.push(relative);
      }
    }
  }
  return orphans.toSorted();
}

export async function checkGenerated(
  options: Pick<
    WriteGeneratedOptions,
    'repoRoot' | 'mappings' | 'declarations'
  > = {},
): Promise<void> {
  const root = options.repoRoot ?? repoRoot;
  const mappings = options.mappings ?? generatedOutputs;
  const declarations = options.declarations ?? distributions;
  const obsoleteOutputs = options.declarations
    ? []
    : obsoleteDistributionOutputs;
  const failures: string[] = [];

  const declared = await buildDeclaredDistributions({
    repoRoot: root,
    declarations,
  });
  try {
    failures.push(
      ...(await checkDeclaredDistributions({
        repoRoot: root,
        built: declared,
      })),
    );
  } finally {
    await cleanupBuiltDistributions(declared);
  }

  for (const output of obsoleteOutputs) {
    const exists = await lstat(path.join(root, output))
      .then(() => true)
      .catch((error: NodeJS.ErrnoException) => {
        if (error.code === 'ENOENT') return false;
        throw error;
      });
    if (exists) {
      failures.push(`${output}: obsolete generated output`);
    }
  }

  for (const mapping of mappings) {
    const result = await buildMapping(mapping, root);
    if (result.status === 'pending') {
      console.log(`${mapping.id}: pending (${result.message})`);
      continue;
    }

    const committed = await readIfExists(result.outputPath);
    if (committed === null) {
      failures.push(`${mapping.output}: missing generated output`);
      continue;
    }

    if (committed !== result.text) {
      const offset = firstDifference(committed, result.text);
      failures.push(
        `${mapping.output}: generated output is stale (first byte difference at ${offset})`,
      );
      continue;
    }

    console.log(`${mapping.id}: in sync`);
  }

  for (const orphan of await findOrphanGeneratedFiles(root, mappings)) {
    failures.push(`${orphan}: orphan generated output`);
  }

  if (failures.length > 0) {
    throw new Error(`Generated output drift detected:\n${failures.join('\n')}`);
  }
}

export interface WriteGeneratedOptions {
  repoRoot?: string;
  mappings?: readonly GeneratedOutput[];
  declarations?: readonly DistributionDeclaration[];
  operations?: PackagingOperations;
  log?: (message: string) => void;
}

export async function writeGenerated(
  options: WriteGeneratedOptions = {},
): Promise<void> {
  const root = options.repoRoot ?? repoRoot;
  const mappings = options.mappings ?? generatedOutputs;
  const declarations = options.declarations ?? distributions;
  const obsoleteOutputs = options.declarations
    ? []
    : obsoleteDistributionOutputs;
  const log = options.log ?? console.log;
  const declared = await buildDeclaredDistributions({
    repoRoot: root,
    declarations,
  });
  const stagingParent = path.join(root, 'node_modules', '.cache');
  await mkdir(stagingParent, { recursive: true });
  const legacyStagingRoot = await mkdtemp(
    path.join(stagingParent, 'generated-files-'),
  );

  try {
    const legacy: StagedReplacement[] = [];
    const initial = new Map<string, BuiltMapping | PendingMapping>();
    for (const mapping of mappings) {
      const result = await buildMapping(mapping, root);
      initial.set(mapping.id, result);
      if (result.status === 'pending') {
        log(`${mapping.id}: pending (${result.message})`);
        continue;
      }
      const stagedPath = path.join(legacyStagingRoot, `${randomUUID()}.mjs`);
      await writeFile(stagedPath, result.text);
      await chmod(stagedPath, result.mode);
      legacy.push(await describeStagedFile(mapping.output, stagedPath));
    }

    await writeStagedOutputs({
      repoRoot: root,
      replacements: [...legacy, ...declared.map(describeBuiltDistribution)],
      obsoleteOutputs,
      operations: options.operations,
      validateBeforeMutation: async () => {
        for (const mapping of mappings) {
          const expected = initial.get(mapping.id);
          if (!expected) {
            throw new Error(
              `Missing staged generated output for ${mapping.id}`,
            );
          }
          const current = await buildMapping(mapping, root);
          if (
            current.status !== expected.status ||
            (current.status === 'built' &&
              expected.status === 'built' &&
              (current.text !== expected.text ||
                current.mode !== expected.mode ||
                current.inputFingerprint !== expected.inputFingerprint))
          ) {
            throw new Error(
              `Generated-output inputs changed before publication for ${mapping.id}`,
            );
          }
        }
        await validateBuiltDistributions({ repoRoot: root, built: declared });
      },
    });
    for (const orphan of await findOrphanGeneratedFiles(root, mappings)) {
      await rm(path.join(root, orphan), { force: true });
      log(`${orphan}: removed orphan generated output`);
    }
    for (const mapping of mappings) {
      if (initial.get(mapping.id)?.status === 'built')
        log(`${mapping.id}: wrote ${mapping.output}`);
    }
    for (const unit of declared) {
      log(`${unit.declaration.owner}: wrote ${unit.target.output}`);
    }
  } finally {
    await cleanupBuiltDistributions(declared);
    await rm(legacyStagingRoot, { recursive: true, force: true });
  }
}

export async function runBuildGenerated(
  argv: readonly string[] = process.argv.slice(2),
): Promise<void> {
  const options = parseArgs(argv);
  if (options.help) {
    process.stdout.write(usage());
    return;
  }

  if (options.listOutputs) {
    process.stdout.write(`${generatedOutputRoots.join('\n')}\n`);
  } else if (options.check) {
    await checkGenerated();
  } else {
    await writeGenerated();
  }
}

const invokedPath = process.argv[1];
if (
  invokedPath &&
  path.resolve(invokedPath) === fileURLToPath(import.meta.url)
) {
  runBuildGenerated().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
